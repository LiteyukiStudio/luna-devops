import type { TFunction } from 'i18next'
import type { FieldErrors } from 'react-hook-form'
import type { AppTemplate, AppTemplateDataVolume, AppTemplateInstallPayload, AppTemplateValueDefinition } from '@/api'
import { z } from 'zod'
import { APPLICATION_IDENTIFIER_MAX_LENGTH, APPLICATION_IDENTIFIER_MIN_LENGTH } from '@/lib/identifier-limits'

export const INSTALL_STAGES = ['prod', 'staging', 'test', 'dev'] as const

/** 构建当前模板的安装表单校验；系统组件、多组件和需要数据卷的模板各自只校验真正提交的字段。 */
export function createInstallFormSchema(template: AppTemplate, t: TFunction) {
  const systemComponent = isSystemComponentTemplate(template)
  const multiComponent = isMultiComponentTemplate(template)
  const identifierMaxLength = applicationIdentifierBaseMaxLength(template)
  const requiredValues = template.values.filter(value => value.required && !value.autoGenerate)

  return z.object({
    projectId: z.string(),
    applicationName: z.string(),
    applicationIdentifier: z.string(),
    deploymentName: z.string(),
    stage: z.enum(INSTALL_STAGES),
    clusterId: z.string(),
    imageRef: z.string(),
    replicas: z.number(),
    cpuRequest: z.string(),
    memoryRequest: z.string(),
    projectVolumeId: z.string(),
    componentProjectVolumeIds: z.record(z.string(), z.string()),
    installNow: z.boolean(),
    provisionAccess: z.boolean(),
    values: z.record(z.string(), z.string()),
  }).superRefine((value, ctx) => {
    const issue = (path: (string | number)[], message: string) => ctx.addIssue({ code: 'custom', path, message })

    for (const definition of requiredValues) {
      if (!(value.values[definition.key] ?? '').trim())
        issue(['values', definition.key], t('appTemplatesPage.validation.valueRequired'))
    }

    if (systemComponent) {
      if (!value.clusterId.trim())
        issue(['clusterId'], t('appTemplatesPage.validation.clusterRequired'))
      return
    }

    if (!value.applicationName.trim())
      issue(['applicationName'], t('appTemplatesPage.validation.applicationNameRequired'))
    const identifierLength = value.applicationIdentifier.trim().length
    if (identifierLength < APPLICATION_IDENTIFIER_MIN_LENGTH || identifierLength > identifierMaxLength) {
      issue(['applicationIdentifier'], t('appTemplatesPage.validation.identifierLength', {
        max: identifierMaxLength,
        min: APPLICATION_IDENTIFIER_MIN_LENGTH,
      }))
    }

    if (multiComponent) {
      for (const component of template.components) {
        if (hasProjectVolume(component.dataVolumes) && !value.componentProjectVolumeIds[component.key]?.trim())
          issue(['componentProjectVolumeIds', component.key], t('appTemplatesPage.validation.projectVolumeRequired'))
      }
      return
    }

    if (!value.imageRef.trim())
      issue(['imageRef'], t('appTemplatesPage.validation.imageRequired'))
    if (!Number.isInteger(value.replicas) || value.replicas < 1)
      issue(['replicas'], t('appTemplatesPage.validation.replicasMin'))
    if (hasProjectVolume(template.dataVolumes) && !value.projectVolumeId.trim())
      issue(['projectVolumeId'], t('appTemplatesPage.validation.projectVolumeRequired'))
  })
}

export type InstallFormValues = z.infer<ReturnType<typeof createInstallFormSchema>>

export function defaultInstallFormValues(template: AppTemplate): InstallFormValues {
  const suffix = Math.random().toString(36).slice(2, 8)
  return {
    projectId: '',
    applicationName: template.name,
    applicationIdentifier: normalizeIdentifierInput(`${template.slug}-${suffix}`).slice(0, applicationIdentifierBaseMaxLength(template)).replace(/-+$/, ''),
    deploymentName: 'default',
    stage: 'dev',
    clusterId: '',
    imageRef: template.image,
    replicas: template.defaultReplicas || 1,
    cpuRequest: template.defaultCPU || '1',
    memoryRequest: template.defaultMemory || '1Gi',
    projectVolumeId: '',
    componentProjectVolumeIds: emptyComponentProjectVolumeIds(template),
    installNow: true,
    provisionAccess: false,
    values: Object.fromEntries(template.values.map(value => [value.key, value.autoGenerate ? '' : value.default])),
  }
}

/** 每个需要数据卷的组件都有一个空选择，避免未选择的组件在表单值里缺席。 */
export function emptyComponentProjectVolumeIds(template: Pick<AppTemplate, 'components'>) {
  return Object.fromEntries(template.components.filter(component => hasProjectVolume(component.dataVolumes)).map(component => [component.key, '']))
}

/** 转换为项目空间安装载荷；留空的自动生成参数不提交，由后端生成。 */
export function projectInstallPayload(template: AppTemplate, value: InstallFormValues): AppTemplateInstallPayload {
  const autoGenerated = new Set(template.values.filter(definition => definition.autoGenerate).map(definition => definition.key))
  const payload: AppTemplateInstallPayload = {
    applicationName: value.applicationName,
    applicationIdentifier: value.applicationIdentifier,
    deploymentName: value.deploymentName,
    stage: value.stage,
    clusterId: value.clusterId,
    imageRef: value.imageRef,
    replicas: value.replicas,
    cpuRequest: value.cpuRequest,
    memoryRequest: value.memoryRequest,
    projectVolumeId: value.projectVolumeId,
    componentProjectVolumeIds: value.componentProjectVolumeIds,
    installNow: value.installNow,
    provisionAccess: value.provisionAccess,
    values: Object.fromEntries(Object.entries(value.values).filter(([key, item]) => !(autoGenerated.has(key) && item === ''))),
  }
  if (isMultiComponentTemplate(template)) {
    // 多组件模板按组件定义运行，后端拒绝单镜像、规格和单卷覆盖。
    return { ...payload, imageRef: '', replicas: 0, cpuRequest: '', memoryRequest: '', projectVolumeId: '' }
  }
  return { ...payload, componentProjectVolumeIds: undefined }
}

/** 必填且没有推荐值的模板参数无法默认填好，放在首屏；其余参数收进自定义参数。 */
export function isEssentialTemplateValue(value: AppTemplateValueDefinition) {
  return value.required && !value.autoGenerate && !value.default
}

const advancedProjectFields = ['deploymentName', 'clusterId', 'imageRef', 'replicas', 'cpuRequest', 'memoryRequest', 'projectVolumeId', 'componentProjectVolumeIds', 'installNow'] as const
const advancedSystemFields = ['imageRef', 'provisionAccess'] as const

/** 判断校验错误是否落在默认折叠的自定义参数里，用于提交失败时自动展开。 */
export function hasAdvancedError(template: AppTemplate, errors: FieldErrors<InstallFormValues>) {
  const fields = isSystemComponentTemplate(template) ? advancedSystemFields : advancedProjectFields
  if (fields.some(field => errors[field]))
    return true
  return template.values.some(value => !isEssentialTemplateValue(value) && errors.values?.[value.key])
}

export function isMultiComponentTemplate(template: Pick<AppTemplate, 'components'>) {
  return template.components.length > 0
}

export function isSystemComponentTemplate(template: Pick<AppTemplate, 'kind' | 'systemComponent'>) {
  return template.kind === 'system_component' || Boolean(template.systemComponent)
}

export function hasProjectVolume(dataVolumes: AppTemplateDataVolume[]) {
  return dataVolumes.some(volume => volume.sourceType === 'projectVolume')
}

export function projectVolumeModeOf(dataVolumes: AppTemplateDataVolume[]): 'Block' | 'Filesystem' {
  const declaration = dataVolumes.find(volume => volume.sourceType === 'projectVolume')
  return declaration?.sourceType === 'projectVolume' && declaration.devicePath ? 'Block' : 'Filesystem'
}

/** 多组件模板会把组件 key 追加到应用标识后，基础标识需要为最长的 `-key` 后缀留出长度。 */
export function applicationIdentifierBaseMaxLength(template: Pick<AppTemplate, 'components'>) {
  const longestSuffix = Math.max(0, ...template.components.map(component => component.key.length + 1))
  return APPLICATION_IDENTIFIER_MAX_LENGTH - longestSuffix
}

export function normalizeIdentifierInput(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9-]/g, '-').replace(/-+/g, '-').replace(/^-+/, '')
}
